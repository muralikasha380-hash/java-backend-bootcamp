package Day05;

public class Example {

	    int x, y;

	    public Example() {
	        this.x = 0;
	        this.y = 0;
	    }

	    public Example(int x, int y) {
	        this.x = x;
	        this.y = y;
	    }

	    @Override
	    public String toString() {
	        return "Example{x=" + x + ", y=" + y + "}";
	    }
	}

