package day01;

public class DataTypes {

	public static void main(String[] args) {
		  // Integer Data Types
        byte age = 20;
        short year = 2026;
        int studentId = 1001;
        long phoneNumber = 9876543210L;

        // Floating Point Data Types
        float attendance = 83.5f;
        double cgpa = 7.67;

        // Character Data Type
        char grade = 'B';

        // Boolean Data Type
        boolean isPlaced = false;

        // String (Reference Data Type)
        String studentName = "Murali Krishna";
        String course = "Java Backend Development";

        System.out.println("Student Name : " + studentName);
        System.out.println("Student ID   : " + studentId);
        System.out.println("Age          : " + age);
        System.out.println("Academic Year: " + year);
        System.out.println("Phone Number : " + phoneNumber);
        System.out.println("Course       : " + course);
        System.out.println("Attendance   : " + attendance + "%");
        System.out.println("CGPA         : " + cgpa);
        System.out.println("Grade        : " + grade);
        System.out.println("Placed       : " + isPlaced);
      
    }
	}

